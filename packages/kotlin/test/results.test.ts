import { buildApiIR } from "@specgen/emitter-core";
import { describe, expect, it } from "vitest";
import { transformToKotlin } from "../src/transform/index.js";
import { emitter, Tester } from "./tester.js";

const HEADER = "// Code generated by @specgen/emitter-kotlin. DO NOT EDIT.";

const spec = `
  @service namespace PetStore;
  model Pet { id: int64 }
  @error model ApiError { code: string }
  @error model NotFound { @statusCode _: 404; message: string }
  @route("/pets") interface Pets {
    @get get(@path id: int64): Pet | ApiError;
    @post create(@body pet: Pet): { @statusCode _: 201; @header location: string; @body pet: Pet } | { @statusCode _: 200; @body pet: Pet };
    @delete remove(@path id: int64): void | NotFound;
  }
`;

describe("operation results and errors", () => {
  it("classifies results and errors", async () => {
    const { program } = await Tester.compile(spec);
    const ir = transformToKotlin(program, buildApiIR(program), { package: "com.acme", enumMemberNaming: "UPPER_SNAKE" });
    const [get, create, remove] = ir.services[0].groups[0].operations;

    expect(get.result).toEqual({
      kind: "single",
      type: { text: "Pet", imports: ["com.acme.models.Pet"], nullable: false },
      status: 200,
      contentType: "application/json",
    });
    expect(get.errors).toMatchObject([
      { statusCodes: "default", body: { text: "ApiError" }, exception: { text: "ApiErrorException", imports: ["com.acme.api.ApiErrorException"] } },
    ]);

    expect(create.body?.name).toBe("pet");
    expect(create.result).toMatchObject({
      kind: "sealed",
      type: { text: "CreateResult", imports: ["com.acme.api.CreateResult"] },
      decl: {
        variants: [
          { name: "Created", status: 201, body: { text: "Pet" }, headers: [{ name: "location" }] },
          { name: "Ok", status: 200, body: { text: "Pet" }, headers: [] },
        ],
      },
    });

    expect(remove.result).toEqual({ kind: "single", type: { text: "Unit", imports: [], nullable: false }, status: 204 });
    expect(remove.errors).toMatchObject([{ statusCodes: 404, exception: { text: "NotFoundException" } }]);

    expect(ir.apiPackage).toBe("com.acme.api");
    expect(ir.apiDeclarations.map((d) => [d.kind, d.name])).toEqual([
      ["api-exception", "ApiException"],
      ["exception", "ApiErrorException"],
      ["exception", "NotFoundException"],
      ["result", "CreateResult"],
    ]);
  });

  it("emits result and exception classes", async () => {
    const { outputs } = await emitter().compile(spec);
    expect(outputs["models/com/acme/api/CreateResult.kt"]).toBe(`${HEADER}
package com.acme.api

import com.acme.models.Pet

sealed interface CreateResult {
    data class Created(val body: Pet, val location: String) : CreateResult
    data class Ok(val body: Pet) : CreateResult
}
`);
    expect(outputs["models/com/acme/api/NotFoundException.kt"]).toBe(`${HEADER}
package com.acme.api

import com.acme.models.NotFound

class NotFoundException(
    val error: NotFound,
    status: Int = 404,
) : ApiException(status)
`);
    expect(outputs["models/com/acme/api/ApiErrorException.kt"]).toContain("    status: Int,\n");
    expect(outputs["models/com/acme/api/ApiException.kt"]).toBe(`${HEADER}
package com.acme.api

/**
 * Base class for HTTP error responses; typed subclasses carry the decoded error body.
 */
open class ApiException(
    val status: Int,
    message: String? = null,
) : RuntimeException(message ?: "HTTP status $status")
`);
  });

  it("emits no api package without services", async () => {
    const { outputs } = await emitter().compile(`model Lonely { x: int32 }`);
    expect(Object.keys(outputs).some((k) => k.includes("/api/"))).toBe(false);
  });
});
